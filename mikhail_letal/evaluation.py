"""Static evaluation: tapered material + piece-square tables, with a mop-up term for bare kings.

The idea behind *tapered* evaluation, for the judge: a piece's worth depends on where it stands, and
where it should stand changes as the game goes on. A king belongs behind its pawns in the
middlegame and in the centre in the endgame; a pawn's advancement matters little early and a great
deal late. So every piece has two tables, a middlegame one (``mg``) and an endgame one (``eg``),
and the position's *phase* (24 with every knight, bishop, rook and queen still on the board, 0 when
only kings and pawns remain) blends them::

    score = (mg * phase + eg * (24 - phase)) / 24

so the evaluation slides smoothly from one table to the other as material comes off, instead of
jumping when some threshold is crossed. Material values are folded into the tables at load time,
so the hot loop does one table lookup per piece per phase.

Scores are centipawns from the point of view of the side to move (negamax convention), so the
search can treat every node the same way.

The tables come from ``weights/pst.json``, generated by ``tools/gen_pst.py`` from a parametric
geometric prior (see its ``_provenance`` object). No table entry is copied from any engine.

On top of the tables, v0.2 adds a handful of *structural* terms that a table indexed by one
square cannot express, because each depends on where other pieces stand: passed pawns (no enemy
pawn can stop them), doubled and isolated pawns, the bishop pair, rooks on open files and the
pawn shield in front of the king. They are all computed from bitboards with shifts and masks,
their weights are listed in ``STRUCTURE_WEIGHTS`` with a one-line reason each, and the whole
group sits behind ``STRUCTURE_TERMS`` so its effect can be measured in games.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import chess

MATE_SCORE = 100_000
MATE_THRESHOLD = MATE_SCORE - 1_000
DRAW_SCORE = 0
PHASE_TOTAL = 24  # sum of the phase weights over the full board: 4*N + 4*B + 4*R + 2*Q

# Switch for the structural terms below: a plain constant (no environment variables are read).
STRUCTURE_TERMS = True  # switch for bisection in development; the shipped value is True

# Weights of the structural terms, in centipawns. What each term measures is in its comment. The
# values are the hand-chosen textbook-magnitude prior (a pawn is 100), also recorded in
# tools/gen_pst.py STRUCTURE_PRIOR. tools/tune_texel.py can refit them toward that prior, and then
# rewrites the numbers and the provenance line below; its fits of 2026-09-07 lost to v0.2 in the
# arena (DECISIONS.md), so the prior ships.
# tuned-by: tools/gen_pst.py prior, untuned (tune_texel.py fits of 2026-09-07 rejected in the arena)
STRUCTURE_WEIGHTS: dict[str, int] = {
    # Per rank a passed pawn has advanced (2nd rank = 1 ... 7th rank = 6). Modest in the
    # middlegame, where pieces can still blockade it ...
    "passed_pawn_mg": 10,
    # ... and twice that in the endgame, where running the passer is usually the whole plan.
    "passed_pawn_eg": 20,
    # Per pawn standing behind another own pawn on its file: the two block each other and only
    # one of them can ever be defended by a neighbour.
    "doubled_pawn": 12,
    # Per pawn with no own pawn on either adjacent file: it can only be defended by pieces.
    "isolated_pawn": 15,
    # Two bishops cover squares of both colours; together they are worth more than the sum.
    "bishop_pair": 30,
    # A rook on a file with no pawns at all reaches the enemy camp along it.
    "rook_open_file": 20,
    # A rook on a file with no own pawn presses on the enemy pawn that is there.
    "rook_semi_open_file": 10,
    # Middlegame only: per own pawn on the king's file or its neighbours, one or two ranks
    # ahead of the king. The pawns keep checks and mating attacks away from the king.
    "king_shield": 10,
}

# Switch for the king-danger term, separate from STRUCTURE_TERMS so the two can be measured apart.
KING_DANGER_TERM = True

# Switch the whole hand-crafted evaluation for the trained network in ``weights/net.npz``.
# ``fasteval`` mirrors this through ``misc[E_NNUE_ON]``, and ``evaluate`` below dispatches on it
# so that this module stays the specification the compiled port is compared against: with the
# switch on, ``tests/test_fasteval.py`` compares two networks rather than a network against a
# hand-crafted evaluation, which is the only way that gate keeps meaning anything.
# A replacement, not a term: when it is on, none of the weights above are read. It exists as a
# switch so a screen can play one against the other rather than the network replacing them on
# faith. False until a screen says otherwise.
USE_NETWORK = False

# How much attacking force bears on the squares around a king, in "attack units". Each enemy
# knight, bishop, rook or queen whose attacks reach the king's zone contributes its unit weight
# once, however many zone squares it hits; the penalty is then quadratic in the total, because
# what mates a king is several pieces arriving together rather than any one of them.
#
# These are textbook magnitudes relative to each other (a queen is the piece that mates, a rook
# next, minors least), on the same footing as the 100/320/330/500/900 piece values: a hand-chosen
# prior, not a fit, and not copied from another engine's table. Index by python-chess piece type.
KING_ATTACK_UNITS: list[int] = [0, 0, 2, 2, 3, 5, 0]  # -  P  N  B  R  Q  K

# Centipawns per unit squared. With three pieces on the zone (N+B+Q = 9 units) this is 162 cp,
# about a minor piece: enough to refuse the position Yan's round-70 analysis found us walking into,
# and not so large that it outweighs real material.
KING_DANGER_SCALE = 2

# The term never exceeds this, so that a pile-up of attackers cannot swamp the material it is
# meant to qualify. 500 cp is just under a rook: a king can be in serious danger, but a positional
# term should not on its own claim more than the exchange plus a pawn.
KING_DANGER_CAP = 500

# Yan's transferable result (handoff/FINDING-king-safety.md): skipping the whole term while the
# king still sits behind this many of its own shield pawns took the cost from -23% to -5% on the
# interpreted engine, because in ordinary middlegames it then never runs. Whether the gate is still
# worth its blindness now that an evaluation costs 204 ns rather than 8.3 us is a question for the
# arena, so it is a named constant rather than an inlined 2.
KING_DANGER_SHELTERED_PAWNS = 2

# Pawn-structure results (passed, doubled, isolated pawns for both sides, from White's view) by
# (white pawns, black pawns) bitboards. Pawn structures change far less often than positions,
# so most evaluations find their structure here. Emptied when it reaches this many entries.
PAWN_CACHE_MAX_ENTRIES = 50_000
_PAWN_CACHE: dict[tuple[int, int], tuple[int, int]] = {}

# Bitboard constants: every square, one full file, and the two edge files.
_ALL = chess.BB_ALL
_FILE_A = chess.BB_FILE_A
_FILE_H = chess.BB_FILE_H
_RANK_1 = chess.BB_RANK_1
_FILE_STRIPE = 0x0101_0101_0101_0101  # one bit per rank on the a-file; a multiplier that
# spreads a rank-1 byte of file bits onto whole files


def _shield_masks(colour: chess.Color) -> list[int]:
    """For every king square, the squares of the king's pawn shield: the king's file and its
    neighbours, one and two ranks ahead of the king (towards the enemy)."""
    masks = []
    for square in range(64):
        file_index = square & 7
        rank_index = square >> 3
        files = chess.BB_FILES[file_index]
        if file_index > 0:
            files |= chess.BB_FILES[file_index - 1]
        if file_index < 7:
            files |= chess.BB_FILES[file_index + 1]
        step = 1 if colour == chess.WHITE else -1
        ranks = 0
        for ahead in (1, 2):
            rank = rank_index + step * ahead
            if 0 <= rank <= 7:
                ranks |= chess.BB_RANKS[rank]
        masks.append(files & ranks)
    return masks


_SHIELD = (_shield_masks(chess.BLACK), _shield_masks(chess.WHITE))  # indexed by colour

# The king's zone: the king's own square and the up-to-eight squares around it. Enemy attacks
# reaching into this 3x3 box are what the king-danger term counts.
_KING_ZONE: list[int] = [chess.BB_KING_ATTACKS[sq] | chess.BB_SQUARES[sq] for sq in range(64)]

# Piece letters in python-chess piece-type order (PAWN = 1 .. KING = 6); index 0 is unused.
_PIECE_LETTERS = " PNBRQK"

_DEFAULT_PATH = Path(__file__).resolve().parent.parent / "weights" / "pst.json"

# Manhattan distance from each square to the nearest of the four centre squares (d4 e4 d5 e5):
# 0 in the centre, 6 in the corners. Used by the mop-up term to drive a bare king to the edge.
_CENTRE_DISTANCE: list[int] = [
    min(abs(sq % 8 - 3), abs(sq % 8 - 4)) + min(abs(sq // 8 - 3), abs(sq // 8 - 4))
    for sq in range(64)
]


@dataclass(frozen=True)
class Tables:
    """Everything ``evaluate`` needs, precomputed once at load.

    ``mg``/``eg`` are indexed ``[colour][piece_type][square]`` with ``colour`` 0 = Black, 1 = White
    (python-chess's ``BLACK``/``WHITE`` are ``False``/``True``). Each entry already includes the
    piece's material value. The Black tables are the White tables with the squares mirrored, so a
    Black piece on ``sq`` is read directly at ``sq`` with no per-piece flip in the hot loop.
    """

    piece_values_mg: list[int]  # indexed by piece type (index 0 unused)
    piece_values_eg: list[int]
    mg: tuple[list[list[int]], list[list[int]]]
    eg: tuple[list[list[int]], list[list[int]]]
    phase_weights: list[int]  # indexed by piece type; zero for pawns and kings
    mopup_edge: int
    mopup_close: int


def _int_list(values: Any, length: int, what: str) -> list[int]:
    if not isinstance(values, list) or len(values) != length:
        raise ValueError(f"{what}: expected a list of {length} integers")
    return [int(v) for v in values]


def _by_piece_type(mapping: Any, what: str) -> list[int]:
    """Turn a ``{"P": .., "N": .., ...}`` object into a list indexed by piece type (missing = 0)."""
    if not isinstance(mapping, dict):
        raise ValueError(f"{what}: expected an object keyed by piece letter")
    return [0] + [int(mapping.get(letter, 0)) for letter in _PIECE_LETTERS[1:]]


def load_tables(path: Path | None = None) -> Tables:
    """Read ``weights/pst.json`` and build the combined (material + square) tables.

    Called once at import; the module-level ``TABLES`` is what ``evaluate`` uses.
    """
    with (path or _DEFAULT_PATH).open(encoding="utf-8") as fh:
        data: dict[str, Any] = json.load(fh)

    values_mg = _by_piece_type(data["piece_values_mg"], "piece_values_mg")
    values_eg = _by_piece_type(data["piece_values_eg"], "piece_values_eg")
    phase_weights = _by_piece_type(data["phase_weights"], "phase_weights")
    full_board = 2 * (
        2 * phase_weights[chess.KNIGHT]
        + 2 * phase_weights[chess.BISHOP]
        + 2 * phase_weights[chess.ROOK]
        + phase_weights[chess.QUEEN]
    )
    if full_board != PHASE_TOTAL:
        raise ValueError(
            f"phase_weights sum to {full_board} over the full board, not {PHASE_TOTAL}"
        )

    def combined(pst_key: str, values: list[int]) -> tuple[list[list[int]], list[list[int]]]:
        white: list[list[int]] = [[]]  # index 0 unused
        black: list[list[int]] = [[]]
        for piece_type in chess.PIECE_TYPES:
            letter = _PIECE_LETTERS[piece_type]
            pst = _int_list(data[pst_key][letter], 64, f"{pst_key}.{letter}")
            white.append([values[piece_type] + pst[sq] for sq in range(64)])
            black.append([values[piece_type] + pst[sq ^ 56] for sq in range(64)])
        return black, white

    mopup = data["mopup"]
    return Tables(
        piece_values_mg=values_mg,
        piece_values_eg=values_eg,
        mg=combined("pst_mg", values_mg),
        eg=combined("pst_eg", values_eg),
        phase_weights=phase_weights,
        mopup_edge=int(mopup["edge"]),
        mopup_close=int(mopup["close"]),
    )


TABLES = load_tables()

# Hot-loop bindings. One row per piece type in python-chess order (pawn first, king last):
# (white mg table, white eg table, black mg table, black eg table).
_ROWS: tuple[tuple[list[int], list[int], list[int], list[int]], ...] = tuple(
    (TABLES.mg[1][pt], TABLES.eg[1][pt], TABLES.mg[0][pt], TABLES.eg[0][pt])
    for pt in chess.PIECE_TYPES
)
_PHASE_N = TABLES.phase_weights[chess.KNIGHT]
_PHASE_B = TABLES.phase_weights[chess.BISHOP]
_PHASE_R = TABLES.phase_weights[chess.ROOK]
_PHASE_Q = TABLES.phase_weights[chess.QUEEN]
_MOPUP_EDGE = TABLES.mopup_edge
_MOPUP_CLOSE = TABLES.mopup_close
# "At least a rook's worth" of non-pawn material triggers the mop-up: a rook or queen, or two
# minors (2 * 320 = 640 >= 500). One minor alone cannot mate and gets nothing.
_MOPUP_MIN_MATERIAL = TABLES.piece_values_mg[chess.ROOK]


_NETWORK: Any = None
_NETWORK_TRIED = False


def _network() -> Any:
    """The trained network, loaded once, or ``None`` when there is no weights file.

    Imported lazily and cached because ``nnue`` imports nothing from here: keeping the dependency
    one-way means the specification can be read without the network and the network without the
    specification.
    """
    global _NETWORK, _NETWORK_TRIED
    if not _NETWORK_TRIED:
        _NETWORK_TRIED = True
        from mikhail_letal import nnue

        path = Path(__file__).resolve().parent.parent / "weights" / "net.npz"
        _NETWORK = nnue.Network.load(path) if path.exists() else None
    return _NETWORK


def is_mate_score(score: int) -> bool:
    return abs(score) >= MATE_THRESHOLD


def game_phase(board: chess.Board) -> int:
    """0 for a king-and-pawn ending up to ``PHASE_TOTAL`` with every piece on; promotions clamp."""
    phase = (
        _PHASE_N * board.knights.bit_count()
        + _PHASE_B * board.bishops.bit_count()
        + _PHASE_R * board.rooks.bit_count()
        + _PHASE_Q * board.queens.bit_count()
    )
    return phase if phase < PHASE_TOTAL else PHASE_TOTAL


def _mopup(board: chess.Board, white: int, black: int, kings: int) -> int:
    """Bonus (from White's view) for the side hunting a bare king in a pawnless ending, else 0.

    Two geometric ideas: the lone king can only be mated on the edge, so reward its distance from
    the centre; and the mating side's king must help, so reward closeness between the kings.
    """
    if board.pawns:
        return 0  # with pawns on the board, promotion is the plan, not a king hunt
    if white & ~kings == 0:
        weak, strong, sign = white, black, -1
    elif black & ~kings == 0:
        weak, strong, sign = black, white, 1
    else:
        return 0
    values = TABLES.piece_values_mg
    material = (
        values[chess.KNIGHT] * (board.knights & strong).bit_count()
        + values[chess.BISHOP] * (board.bishops & strong).bit_count()
        + values[chess.ROOK] * (board.rooks & strong).bit_count()
        + values[chess.QUEEN] * (board.queens & strong).bit_count()
    )
    if material < _MOPUP_MIN_MATERIAL:
        return 0
    weak_king = (kings & weak).bit_length() - 1
    strong_king = (kings & strong).bit_length() - 1
    kings_apart = chess.square_manhattan_distance(weak_king, strong_king)
    return sign * (_MOPUP_EDGE * _CENTRE_DISTANCE[weak_king] + _MOPUP_CLOSE * (14 - kings_apart))


def _fill_south(bb: int) -> int:
    """Every square at or below (towards rank 1) a set bit, on the same file."""
    bb |= bb >> 8
    bb |= bb >> 16
    bb |= bb >> 32
    return bb


def _fill_north(bb: int) -> int:
    """Every square at or above (towards rank 8) a set bit, on the same file."""
    bb |= bb << 8
    bb |= bb << 16
    bb |= bb << 32
    return bb & _ALL


def _isolated_count(pawns: int) -> int:
    """How many of ``pawns`` have no pawn of the same set on an adjacent file."""
    # Squash the pawns onto rank 1: one bit per occupied file.
    files = _fill_south(pawns) & _RANK_1
    neighbours = (files & ~_FILE_A) >> 1 | (files & ~_FILE_H) << 1
    lonely_files = files & ~neighbours
    # Spread the lonely files back over the whole board and count the pawns on them.
    return (pawns & lonely_files * _FILE_STRIPE).bit_count()


def pawn_structure(white_pawns: int, black_pawns: int) -> tuple[int, int]:
    """(middlegame, endgame) pawn-structure score from White's view: passed pawns by rank, less
    doubled and isolated pawns, for both sides. Pure function of the two pawn bitboards.

    A pawn is *passed* when no enemy pawn stands ahead of it on its own or an adjacent file. The
    squares an enemy pawn controls or blocks on its way down the board are its file and the two
    neighbouring files below it; filling those from every enemy pawn and taking the complement
    leaves exactly the squares from which a pawn is passed.
    """
    weights = STRUCTURE_WEIGHTS
    passed_mg = weights["passed_pawn_mg"]
    passed_eg = weights["passed_pawn_eg"]

    # Squares in front of (and diagonally in front of) black pawns, seen from White: no white
    # pawn there is passed. Symmetrically for black pawns with a north fill of the white pawns.
    black_span = _fill_south(black_pawns) >> 8
    black_span |= (black_span & ~_FILE_A) >> 1 | (black_span & ~_FILE_H) << 1
    white_span = _fill_north(white_pawns) << 8 & _ALL
    white_span |= (white_span & ~_FILE_A) >> 1 | (white_span & ~_FILE_H) << 1

    mg = 0
    eg = 0
    bb = white_pawns & ~black_span
    while bb:
        lsb = bb & -bb
        advance = lsb.bit_length() - 1 >> 3  # rank index: 1 on the 2nd rank ... 6 on the 7th
        mg += passed_mg * advance
        eg += passed_eg * advance
        bb ^= lsb
    bb = black_pawns & ~white_span
    while bb:
        lsb = bb & -bb
        advance = 7 - (lsb.bit_length() - 1 >> 3)
        mg -= passed_mg * advance
        eg -= passed_eg * advance
        bb ^= lsb

    # A pawn with an own pawn somewhere above it on the same file is the rear pawn of a doubled
    # (or tripled) pair; counting rear pawns counts each extra pawn on a file exactly once. The
    # count is the same whichever direction is used, so one fill serves both colours.
    doubled = weights["doubled_pawn"]
    both = doubled * (
        (white_pawns & _fill_south(white_pawns) >> 8).bit_count()
        - (black_pawns & _fill_south(black_pawns) >> 8).bit_count()
    )
    isolated = weights["isolated_pawn"]
    both += isolated * (_isolated_count(white_pawns) - _isolated_count(black_pawns))
    # Both penalties count against the side that has them, in both phases.
    return mg - both, eg - both


def _structure(
    white: int, black: int, pawns: int, bishops: int, rooks: int, kings: int
) -> tuple[int, int]:
    """(middlegame, endgame) structural terms from White's view: the pawn structure (cached by
    pawn bitboards), the bishop pair, rooks on open and semi-open files, the king's pawn shield.
    """
    white_pawns = pawns & white
    black_pawns = pawns & black
    key = (white_pawns, black_pawns)
    cached = _PAWN_CACHE.get(key)
    if cached is None:
        if len(_PAWN_CACHE) >= PAWN_CACHE_MAX_ENTRIES:
            _PAWN_CACHE.clear()
        cached = _PAWN_CACHE[key] = pawn_structure(white_pawns, black_pawns)
    mg, eg = cached
    weights = STRUCTURE_WEIGHTS

    pair = weights["bishop_pair"]
    if (bishops & white).bit_count() >= 2:
        mg += pair
        eg += pair
    if (bishops & black).bit_count() >= 2:
        mg -= pair
        eg -= pair

    open_file = weights["rook_open_file"]
    semi_open = weights["rook_semi_open_file"]
    files = chess.BB_FILES
    bb = rooks & white
    while bb:
        lsb = bb & -bb
        file_bb = files[(lsb.bit_length() - 1) & 7]
        if not pawns & file_bb:
            mg += open_file
            eg += open_file
        elif not white_pawns & file_bb:
            mg += semi_open
            eg += semi_open
        bb ^= lsb
    bb = rooks & black
    while bb:
        lsb = bb & -bb
        file_bb = files[(lsb.bit_length() - 1) & 7]
        if not pawns & file_bb:
            mg -= open_file
            eg -= open_file
        elif not black_pawns & file_bb:
            mg -= semi_open
            eg -= semi_open
        bb ^= lsb

    shield = weights["king_shield"]
    white_king = (kings & white).bit_length() - 1
    black_king = (kings & black).bit_length() - 1
    mg += shield * (
        (white_pawns & _SHIELD[1][white_king]).bit_count()
        - (black_pawns & _SHIELD[0][black_king]).bit_count()
    )
    return mg, eg


def _king_danger_one(board: chess.Board, colour: chess.Color, own_pawns: int) -> int:
    """The middlegame penalty, as a positive number, for enemy force bearing on ``colour``'s king.

    Why this term exists: the engine could see far enough and still walk into a mating attack,
    because nothing in the evaluation knew what an attack looked like. Round 70 was lost by
    castling long into a queen that already stood on b3 (handoff/FINDING-king-safety.md); the
    search was not short of depth, it was short of a reason to dislike the position.

    Counted per attacking piece, not per attacked square: a piece that hits three squares of the
    zone is one attacker, because what decides a king hunt is how many pieces arrive, not how much
    of the box each one touches. The total is squared so that the third attacker costs far more
    than the first, which is the whole of the textbook insight about attacks.
    """
    king_square = (board.kings & board.occupied_co[colour]).bit_length() - 1
    if king_square < 0:  # no king: only reachable from a hand-built position, never from play
        return 0

    # The shelter gate. A king still behind its own pawns is not the king this term is about, and
    # skipping it here is what keeps the term affordable (see KING_DANGER_SHELTERED_PAWNS).
    shield = _SHIELD[colour][king_square]
    if (own_pawns & shield).bit_count() >= KING_DANGER_SHELTERED_PAWNS:
        return 0

    zone = _KING_ZONE[king_square]
    enemy = board.occupied_co[not colour]
    units = 0
    # Pawns and the enemy king are deliberately not counted: a pawn beside our king is a storm
    # already paid for by king_shield, and the enemy king is never part of a mating attack.
    attackers = enemy & (board.knights | board.bishops | board.rooks | board.queens)
    while attackers:
        lsb = attackers & -attackers
        square = lsb.bit_length() - 1
        if board.attacks_mask(square) & zone:
            piece_type = board.piece_type_at(square)
            if piece_type is not None:
                units += KING_ATTACK_UNITS[piece_type]
        attackers ^= lsb

    penalty = KING_DANGER_SCALE * units * units
    return penalty if penalty < KING_DANGER_CAP else KING_DANGER_CAP


def king_danger(board: chess.Board, white_pawns: int, black_pawns: int) -> int:
    """The king-danger term from White's view: Black's danger less White's own.

    Middlegame only, like ``king_shield``: the phase blend in ``evaluate_running`` tapers it away
    by itself, because an attack needs the pieces that a king-and-pawn endgame no longer has.
    """
    black_danger = _king_danger_one(board, chess.BLACK, black_pawns)
    white_danger = _king_danger_one(board, chess.WHITE, white_pawns)
    return black_danger - white_danger


def material_pst(board: chess.Board) -> tuple[int, int, int]:
    """The three running totals of the evaluation, computed from scratch.

    Returns ``(mg, eg, phase)``: the middlegame and endgame sums of the combined
    material-plus-square tables from **White's** point of view (White's pieces added, Black's
    subtracted), and the raw phase weight of the pieces on the board. ``phase`` is not clamped
    here — promotions can push it past ``PHASE_TOTAL`` and the blend below clamps it.

    Each colour's bitboard for each piece type is walked with an inlined lowest-set-bit scan (the
    same loop as ``chess.scan_forward`` without the generator overhead).

    ``mikhail_letal.searchboard.SearchBoard`` keeps exactly these three numbers up to date across
    make and unmake, so the search rarely calls this; it is the definition they are checked
    against (``tests/test_searchboard.py``).
    """
    pawns = board.pawns
    knights = board.knights
    bishops = board.bishops
    rooks = board.rooks
    queens = board.queens
    white = board.occupied_co[True]
    black = board.occupied_co[False]

    phase = (
        _PHASE_N * knights.bit_count()
        + _PHASE_B * bishops.bit_count()
        + _PHASE_R * rooks.bit_count()
        + _PHASE_Q * queens.bit_count()
    )

    mg = 0
    eg = 0
    for type_bb, (mg_w, eg_w, mg_b, eg_b) in zip(
        (pawns, knights, bishops, rooks, queens, board.kings), _ROWS, strict=True
    ):
        bb = type_bb & white
        while bb:
            lsb = bb & -bb
            sq = lsb.bit_length() - 1
            mg += mg_w[sq]
            eg += eg_w[sq]
            bb ^= lsb
        bb = type_bb & black
        while bb:
            lsb = bb & -bb
            sq = lsb.bit_length() - 1
            mg -= mg_b[sq]
            eg -= eg_b[sq]
            bb ^= lsb
    return mg, eg, phase


def evaluate_running(board: chess.Board, mg: int, eg: int, phase: int) -> int:
    """The evaluation, given the three running totals of ``material_pst`` for ``board``.

    Everything that is *not* a per-piece table sum happens here: the insufficient-material draw,
    the structural terms, the phase blend and the mop-up bonus. Split out so that a caller which
    maintains ``mg``/``eg``/``phase`` incrementally (see ``searchboard.SearchBoard``) and the
    from-scratch ``evaluate`` below run exactly the same arithmetic on the same inputs, and so
    can never disagree.
    """
    pawns = board.pawns
    rooks = board.rooks
    queens = board.queens
    # Only knights and bishops can be insufficient material, so skip python-chess's two-colour
    # check whenever a pawn, rook or queen is on the board (the semantics are unchanged).
    if not (pawns | rooks | queens) and board.is_insufficient_material():
        return DRAW_SCORE

    kings = board.kings
    white = board.occupied_co[True]
    black = board.occupied_co[False]
    if phase > PHASE_TOTAL:
        phase = PHASE_TOTAL

    if STRUCTURE_TERMS:
        structure_mg, structure_eg = _structure(white, black, pawns, board.bishops, rooks, kings)
        mg += structure_mg
        eg += structure_eg

    # Middlegame only, so it is added to mg alone and the phase blend below tapers it out.
    if KING_DANGER_TERM:
        mg += king_danger(board, pawns & white, pawns & black)

    # Blend the two phases. Truncate toward zero rather than floor so that a position and its
    # colour-swapped mirror get exactly opposite scores (floor division would bias negatives).
    total = mg * phase + eg * (PHASE_TOTAL - phase)
    score = total // PHASE_TOTAL if total >= 0 else -((-total) // PHASE_TOTAL)

    if not pawns:  # cheap gate; the helper re-checks so it is correct on its own too
        score += _mopup(board, white, black, kings)

    return score if board.turn else -score


def evaluate(board: chess.Board) -> int:
    """Static evaluation in centipawns from the side to move's point of view.

    Sums the combined material-plus-square tables for both phases over every piece, adds the
    structural terms when they are switched on, then blends the two phases by the game phase.
    A pure function of the position, and the reference the incremental sums are tested against.

    With ``USE_NETWORK`` on, the trained network replaces all of that -- except the
    insufficient-material draw, which is a rule rather than a judgement and which a network
    trained on evaluations would otherwise score as an advantage.
    """
    if USE_NETWORK:
        network = _network()
        if network is not None:
            if not (board.pawns | board.rooks | board.queens) and board.is_insufficient_material():
                return DRAW_SCORE
            from mikhail_letal import nnue

            return nnue.evaluate(network, board)
    mg, eg, phase = material_pst(board)
    return evaluate_running(board, mg, eg, phase)
